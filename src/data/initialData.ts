export function computeUniformMindmapRadius(
  totalCount: number,
  mode: 'byPosition' | 'byCategory' = 'byPosition'
): number {
  const targetArcSpacing = 240;
  const minRadius = mode === 'byPosition' ? 460 : 380;
  const dynamicRadius = Math.round(
    (Math.max(1, totalCount) * targetArcSpacing) / (2 * Math.PI)
  );
  return Math.max(minRadius, dynamicRadius);
}

export function createInitialMindmapState(
  metadata: MetadataConfig
): MindmapStorageState {
  const byPositionFolders: MindmapStorageState['byPosition']['folders'] = {};
  const totalPos = Math.max(1, metadata.positions.length);
  const radiusPos = computeUniformMindmapRadius(totalPos, 'byPosition');
  const radiusPosX = Math.round(radiusPos * 1.06);
  const radiusPosY = radiusPos;

  metadata.positions.forEach((pos, idx) => {
    const angle = (idx / totalPos) * Math.PI * 2 - Math.PI / 2;
    byPositionFolders[pos.name] = {
      x: Math.round(Math.cos(angle) * radiusPosX),
      y: Math.round(Math.sin(angle) * radiusPosY),
      collapsed: false,
    };
  });

  const byCategoryFolders: MindmapStorageState['byCategory']['folders'] = {};
  const totalCat = Math.max(1, metadata.categories.length);
  const radiusCat = computeUniformMindmapRadius(totalCat, 'byCategory');
  const radiusCatX = Math.round(radiusCat * 1.06);
  const radiusCatY = radiusCat;

  metadata.categories.forEach((cat, idx) => {
    const angle = (idx / totalCat) * Math.PI * 2 - Math.PI / 2;
    byCategoryFolders[cat] = {
      x: Math.round(Math.cos(angle) * radiusCatX),
      y: Math.round(Math.sin(angle) * radiusCatY),
      collapsed: false,
    };
  });

  return {
    byPosition: {
      folders: byPositionFolders,
      cardOffsets: {},
    },
    byCategory: {
      folders: byCategoryFolders,
      cardOffsets: {},
    },
  };
}
